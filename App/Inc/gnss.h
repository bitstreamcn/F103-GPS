union u_Short
{
	uint8_t bytes[2];
	unsigned short uShort;
};

union i_Short
{
	uint8_t bytes[2];
	signed short iShort;
};

union u_Long
{
	uint8_t bytes[4];
	unsigned long uLong;
};

union i_Long
{
	uint8_t bytes[4];
	signed long iLong;
};

//数据参考  https://github.com/SimpleMethod/STM32-GNSS/blob/master/doc/u-blox8-M8_ReceiverDescrProtSpec_(UBX-13003221).pdf

typedef struct
{
	uint8_t uniqueID[5] = {0, 0, 0, 0, 0};
	uint8_t uartWorkingBuffer[180];

	unsigned long iTOW; // 🚨 新增：GPS 毫秒级时间戳
	unsigned short year;
	uint8_t yearBytes[2];
	uint8_t month;
	uint8_t day;
	uint8_t hour;
	uint8_t min;
	uint8_t sec;
	uint8_t fixType; //0=无定位，2=2D定位，3=3D定位，4=GNSS+DR组合，5=RTK浮点，6=RTK固定。飞控必须判断此值 ≥3 才能使用 GPS 数据

	// 🚨 新增：参与定位的卫星数量
	uint8_t numSV;

	signed long lon;
	uint8_t lonBytes[4];
	signed long lat;
	uint8_t latBytes[4];
	float fLon; //float 类型的真实度数（如 113.987654f）
	float fLat;

	signed long height; //相对于地球数学模型椭球面的高度（单位：毫米）
	signed long hMSL;   //海拔高度。相对于平均海平面的高度（单位：毫米）。飞控通常用这个值与气压计或 IMU 融合来定高。
	uint8_t hMSLBytes[4];
	unsigned long hAcc; //水平定位精度因子（单位：毫米）。例如 hAcc = 500 表示水平误差在 0.5 米左右。飞控可用此值判断 GPS 信号好不好，太差就降低 GPS 权重。
	unsigned long vAcc; //垂直定位精度因子（单位：毫米）。

    // 新增：北向速度和东向速度 (单位: mm/s)
    signed long velN;  //北向速度（单位：毫米/秒）。向北为正，向南为负。
    signed long velE;  //东向速度（单位：毫米/秒）。向东为正，向西为负。
    //垂直向下的速度
    signed long velD;  //垂直向下的速度（单位：毫米/秒）。向下（降落）为正，向上（爬升）为负。可用于辅助气压计进行高度变化率控制。

	signed long gSpeed;//二维地面速度（单位：毫米/秒）。即水平移动的标量速度大小（不管方向）。
	uint8_t gSpeedBytes[4];
	signed long headMot;//运动航向角。模块算好的运动方向（0=北，90=东）。注意：在低速时误差极大，所以我们在代码里通常不用它，而是用 velN 和 velE 自己算。

	uint32_t update_tick;

}GNSS_StateHandle;

extern GNSS_StateHandle GNSS_Handle;

